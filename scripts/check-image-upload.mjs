import fs from "node:fs";
import assert from "node:assert/strict";
import ts from "typescript";
const module={exports:{}};
new Function("exports","module",ts.transpileModule(fs.readFileSync("lib/upload-image.ts","utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(module.exports,module);
const {prepareUploadImage,MAX_UPLOAD_BYTES}=module.exports;
let width=4000,height=3000,closed=0,attempts=0;
globalThis.createImageBitmap=async()=>({width,height,close(){closed++}});
globalThis.document={createElement(){return {width:0,height:0,getContext(){return {drawImage(){}}},toBlob(callback,type){attempts++;callback(new Blob([new Uint8Array(attempts===1?MAX_UPLOAD_BYTES+1:1000)],{type}))}}}};
const source=new File([new Uint8Array(6_000_000)],"large.png",{type:"image/png"});
const result=await prepareUploadImage(source);
assert.ok(result.size<=MAX_UPLOAD_BYTES);assert.equal(result.type,"image/png");assert.equal(result.name,source.name);assert.equal(attempts,2);assert.equal(closed,1);
width=800;height=600;
const small=new File(["small"],"small.jpg",{type:"image/jpeg"});
assert.equal(await prepareUploadImage(small),small);assert.equal(closed,2);
await assert.rejects(prepareUploadImage(new File(["svg"],"bad.svg",{type:"image/svg+xml"})),/JPEG or PNG/);
await assert.rejects(prepareUploadImage(new File([new Uint8Array(11*1024*1024)],"huge.png",{type:"image/png"})),/10 MB/);
globalThis.createImageBitmap=async()=>{throw new Error("decode")};
await assert.rejects(prepareUploadImage(small),/could not be opened/);
console.log("Verified upload compression retry, size cap, PNG preservation, unchanged small images, bitmap cleanup, and invalid-file errors.");
